import type { ReactNode } from "react";

/**
 * Пустое значение `<select>` — подсказка, а не пункт: «Выберите счёт».
 *
 * Видна в закрытом поле, пока ничего не выбрано, приглушена (`globals.css`,
 * `data-placeholder`), а в раскрытом списке её нет — `hidden` прячет её там,
 * где браузер это умеет, `disabled` не даёт выбрать там, где нет (Safari). До
 * 27.09.2026 это был обычный пункт: «Выберите счёт» стоял в списке первым
 * наравне с «Кассой», выбирался, и форма отказывала уже при записи.
 *
 * Обычный `<option value="">` в продукте не пишется: управляемое поле — через
 * `ChoiceSelect` (там и крестик «очистить» у необязательного), а этот пункт
 * напрямую — только у списка без состояния (меню-действие, разбор выписки).
 */
export function PlaceholderOption({ children }: { children: ReactNode }) {
  return (
    <option value="" disabled hidden data-placeholder="">
      {children}
    </option>
  );
}
