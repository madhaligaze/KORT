import { numfmt } from "@univerjs/core";

/**
 * Регистрация русской локали в движке форматов чисел.
 *
 * Без неё импорт выглядит верно, но читается неправильно, и это худший из
 * возможных видов расхождения — цифры на месте, а значат другое. В Google
 * ячейка «Дата» показывает «пн 01.06.26», а «Приход» — «95 323,00»; тот же
 * образец формата без русской локали даёт «Mon 01.06.26» и «95,323.00».
 * Формат один и тот же, разделители и названия дней — нет.
 *
 * Названия месяцев в родительном падеже («января», не «январь») — потому что
 * образец `d mmmm yyyy` в русском читается как «1 июня 2026», а не «1 июнь».
 *
 * Пара к этому — префикс `[$-419]`, который импорт приписывает образцам формата
 * (`xlsx/convert.ts`). Регистрация здесь без префикса там ничего не даёт: движок
 * берёт локаль из самого образца.
 */
const RU = {
  ddd: ["вс", "пн", "вт", "ср", "чт", "пт", "сб"],
  dddd: ["воскресенье", "понедельник", "вторник", "среда", "четверг", "пятница", "суббота"],
  mmm: ["янв", "фев", "мар", "апр", "май", "июн", "июл", "авг", "сен", "окт", "ноя", "дек"],
  mmmm: [
    "января",
    "февраля",
    "марта",
    "апреля",
    "мая",
    "июня",
    "июля",
    "августа",
    "сентября",
    "октября",
    "ноября",
    "декабря",
  ],
  ampm: ["AM", "PM"],
  bool: ["ИСТИНА", "ЛОЖЬ"],
  // Неразрывный пробел, а не обычный: именно его ставит Google, и по обычному
  // пробелу число разрывалось бы переносом строки посреди разряда.
  group: " ",
  decimal: ",",
  nan: "NaN",
  infinity: "∞",
  percent: "%",
  positive: "+",
  negative: "-",
  exponent: "E",
  preferMDY: false,
};

// Казахская локаль книг ГК BBC совпадает с русской по разделителям — отдельный
// набор нужен только ради названий дней и месяцев.
const KK = {
  ...RU,
  ddd: ["жс", "дс", "сс", "ср", "бс", "жм", "сн"],
  dddd: ["жексенбі", "дүйсенбі", "сейсенбі", "сәрсенбі", "бейсенбі", "жұма", "сенбі"],
  mmm: ["қаң", "ақп", "нау", "сәу", "мам", "мау", "шіл", "там", "қыр", "қаз", "қар", "жел"],
  mmmm: [
    "қаңтар",
    "ақпан",
    "наурыз",
    "сәуір",
    "мамыр",
    "маусым",
    "шілде",
    "тамыз",
    "қыркүйек",
    "қазан",
    "қараша",
    "желтоқсан",
  ],
};

let registered = false;

/** Идемпотентно: вызывается при каждом монтировании таблицы. */
export function registerRuNumfmtLocale() {
  if (registered) return;
  registered = true;
  try {
    numfmt.addLocale(RU, "ru");
    numfmt.addLocale(KK, "kk");
  } catch {
    // Движок форматов — не то, ради чего стоит ронять экран: без локали
    // числа покажутся в английской раскладке, но покажутся.
  }
}
